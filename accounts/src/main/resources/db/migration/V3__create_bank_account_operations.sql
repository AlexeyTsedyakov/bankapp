CREATE TABLE bank_account_operations
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id      BIGINT                                  NOT NULL,
    idempotency_key UUID                                    NOT NULL,
    operation_type  VARCHAR(32)                             NOT NULL,
    amount          DECIMAL(19, 2)                          NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_bank_account_operations PRIMARY KEY (id),
    CONSTRAINT uq_bank_account_operation_idempotency_key UNIQUE (idempotency_key, operation_type),
    CONSTRAINT chk_bank_account_operation_amount_non_negative CHECK (amount >= 0),
    CONSTRAINT fk_bank_account_operation_on_bank_account
        FOREIGN KEY (account_id) REFERENCES bank_accounts (id) ON DELETE CASCADE
);
